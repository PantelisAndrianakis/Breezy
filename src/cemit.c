/* A growable text buffer. */
typedef struct
{
	char  *p;
	size_t n;
	size_t cap;
} CBuf;

static void cbuf_printf(CBuf *b, const char *fmt, ...)
{
	va_list ap;
	va_start(ap, fmt);
	int need = vsnprintf(NULL, 0, fmt, ap);
	va_end(ap);
	if (b->n + (size_t)need + 1 > b->cap)
	{
		size_t cap = b->cap ? b->cap : 4096;
		while (b->n + (size_t)need + 1 > cap)
		{
			cap *= 2;
		}

		b->p = realloc(b->p, cap);
		b->cap = cap;
	}

	va_start(ap, fmt);
	vsnprintf(b->p + b->n, (size_t)need + 1, fmt, ap);
	va_end(ap);
	b->n += (size_t)need;
}

static void cbuf_free(CBuf *b)
{
	free(b->p);
	b->p = NULL;
	b->n = 0;
	b->cap = 0;
}

