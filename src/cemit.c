#define CEMIT_MAX_LOCALS 256

/* Translation state for one unit. */
typedef struct
{
	CBuf        out;                          /* The unit's statement text. */
	int         ok;                           /* Cleared on the first unsupported construct. */
	int         region;                       /* 1: region unit (bounds failures report through fp). */
	int         tmp;                          /* Counter for statement-expression temporaries. */
	int         nfinal;
	int         finals[64];                   /* Final tables the unit indexes (table index). */
	const char *ret_wide;                     /* Whole function: C return type (NULL for void). */
	const char *ret_narrow;                   /* Whole function: Breezy return type in C. */
	const Func *fn;                           /* The enclosing function, for its constant locals. */
	int         nconst;
	int         const_off[CEMIT_MAX_LOCALS];  /* Memo of locals already asked about. */
	char        const_known[CEMIT_MAX_LOCALS];
	long long   const_val[CEMIT_MAX_LOCALS];
	int         nlocal;
	int         local_off[CEMIT_MAX_LOCALS];  /* Frame offset of each referenced local. */
	TypeKind    local_kind[CEMIT_MAX_LOCALS]; /* Its type. */
	int         loops;                        /* Depth of enclosing loops at the statement being emitted. */
	int         fe;                           /* Counter naming each foreach's C temporaries. */
	int         ncallee;
	FuncInfo   *callees[16];                  /* Whole-C functions the unit calls (each needs a prototype). */
} CUnit;

static const char *c_param_type(TypeKind k);

/* The C type holding a Breezy scalar or array reference, or NULL. */
static const char *c_type(TypeKind k)
{
	switch (k)
	{
	case TY_BYTE:
		return "int8_t";
	case TY_SHORT:
		return "int16_t";
	case TY_INT:
		return "int32_t";
	case TY_LONG:
		return "int64_t";
	case TY_UBYTE:
		return "uint8_t";
	case TY_USHORT:
		return "uint16_t";
	case TY_UINT:
		return "uint32_t";
	case TY_ULONG:
		return "uint64_t";
	case TY_BOOL:
		return "int64_t";
	case TY_DOUBLE:
		return "double";
	case TY_ARRAY:
	case TY_GENERIC:
		return "char *";
	default:
		return NULL;
	}
}

/* The C type of one array element: bool elements are single bytes. */
static const char *c_elem_type(TypeKind k)
{
	if (k == TY_BOOL)
	{
		return "uint8_t";
	}

	if (k == TY_ARRAY)
	{
		return NULL;
	}

	return c_type(k);
}

/* Records that the unit reads or writes the local at frame offset off. */
static void note_local(CUnit *u, int off, TypeKind k)
{
	for (int i = 0; i < u->nlocal; i++)
	{
		if (u->local_off[i] == off)
		{
			if (u->local_kind[i] != k)
			{
				u->ok = 0;
			}

			return;
		}
	}

	if (u->nlocal == CEMIT_MAX_LOCALS)
	{
		u->ok = 0;
		return;
	}

	u->local_off[u->nlocal] = off;
	u->local_kind[u->nlocal] = k;
	u->nlocal++;
}

/* A literal integer, possibly negated. */
static int c_const_int(const Expr *e, long long *out)
{
	if (e->kind == EX_INT)
	{
		*out = e->int_val;
		return 1;
	}

	if (e->kind == EX_UNARY && e->op == TOKEN_MINUS && e->lhs && e->lhs->kind == EX_INT)
	{
		*out = -e->lhs->int_val;
		return 1;
	}

	return 0;
}

/**
 * 1 and the value when the local at frame offset off is a function-level constant (every assignment to it is the same integer literal), the same fact the IR path folds.
 * Answers are memoized per unit.
 */
static int c_local_const(CUnit *u, int off, long long *out)
{
	if (!u->fn)
	{
		return 0;
	}

	for (int i = 0; i < u->nconst; i++)
	{
		if (u->const_off[i] == off)
		{
			*out = u->const_val[i];
			return u->const_known[i];
		}
	}

	long long v = 0;
	int known = ir_func_const_local(u->fn, off, &v);
	if (u->nconst < CEMIT_MAX_LOCALS)
	{
		u->const_off[u->nconst] = off;
		u->const_known[u->nconst] = (char)known;
		u->const_val[u->nconst] = v;
		u->nconst++;
	}

	*out = v;
	return known;
}

/* A literal integer, or a read of a constant local. */
static int c_const_value(CUnit *u, const Expr *e, long long *out)
{
	if (c_const_int(e, out))
	{
		return 1;
	}

	return e->kind == EX_IDENT && !e->anno_capture && e->anno_int > 0 && ty_is_int(e->type.kind)
		   && c_local_const(u, e->anno_int, out);
}

static void c_expr(CUnit *u, const Expr *e);

/**
 * arr[i] as an lvalue.
 * A statement expression evaluates the array and the index once, applies the bounds check unless BCE proved it, and yields the element pointer.
 * A failing check reports through the enclosing Breezy frame: pc is one byte before the region call's return address, frame is fp.
 */
/* Records that the unit reads final table idx. */
static void note_final(CUnit *u, int idx)
{
	for (int i = 0; i < u->nfinal; i++)
	{
		if (u->finals[i] == idx)
		{
			return;
		}
	}

	if (u->nfinal == 64)
	{
		u->ok = 0;
		return;
	}

	u->finals[u->nfinal++] = idx;
}

/* Defines final table idx as a static const C array, once per translation unit. */
static void c_emit_final(int idx)
{
	if (idx >= g_fin_cap)
	{
		int cap = g_fin_cap ? g_fin_cap : 16;
		while (cap <= idx)
		{
			cap *= 2;
		}

		g_fin_done = realloc(g_fin_done, (size_t)cap);
		memset(g_fin_done + g_fin_cap, 0, (size_t)(cap - g_fin_cap));
		g_fin_cap = cap;
	}

	if (g_fin_done[idx])
	{
		return;
	}

	g_fin_done[idx] = 1;
	const FinalTable *ft = final_table(idx);
	const char *et = c_elem_type(ft->elem);
	cbuf_printf(&g_src, "\nstatic const %s bzy_fin_%d[%d] = {", et, idx, ft->count > 0 ? ft->count : 1);
	for (int k = 0; k < ft->count; k++)
	{
		if (ft->elem == TY_DOUBLE)
		{
			cbuf_printf(&g_src, "%s%.17g", k ? ", " : " ", ft->dvals[k]);
		}
		else
		{
			cbuf_printf(&g_src, "%s(%s)0x%llxULL", k ? ", " : " ", et, (unsigned long long)ft->ivals[k]);
		}
	}

	cbuf_printf(&g_src, "%s };\n", ft->count > 0 ? "" : " 0");
}

static void c_index_lvalue(CUnit *u, const Expr *e)
{
	const char *et = c_elem_type(e->type.kind);
	if (!et || e->lhs->type.kind != TY_ARRAY)
	{
		u->ok = 0;
		return;
	}

	if (e->lhs->anno_final)
	{
		// A final array: index its static const table directly; the count is a compile-time constant and the frame slot is never touched.
		int idx = e->lhs->anno_final - 1;
		const FinalTable *ft = final_table(idx);
		note_final(u, idx);
		int k = u->tmp++;
		cbuf_printf(&u->out, "(*({ int64_t i%d_ = (int64_t)", k);
		c_expr(u, e->rhs);
		cbuf_printf(&u->out, "; ");
		if (!e->anno_index_safe)
		{
			if (!u->region)
			{
				u->ok = 0;
				return;
			}

			cbuf_printf(&u->out, "if (__builtin_expect((uint64_t)i%d_ >= (uint64_t)%dULL, 0)) ", k, ft->count);
			cbuf_printf(&u->out, "{ bzy_oob(i%d_, %d, (int64_t)(ra - 1), (int64_t)fp); } ", k, ft->count);
		}

		cbuf_printf(&u->out, "&bzy_fin_%d[i%d_]; }))", idx, k);
		return;
	}

	if (!e->anno_index_safe && !u->region)
	{
		u->ok = 0; // A whole C function has no Breezy frame to report a bounds failure through.
		return;
	}

	int k = u->tmp++;
	cbuf_printf(&u->out, "(*({ char *a%d_ = ", k);
	c_expr(u, e->lhs);
	cbuf_printf(&u->out, "; int64_t i%d_ = (int64_t)", k);
	c_expr(u, e->rhs);
	cbuf_printf(&u->out, "; ");
	if (!e->anno_index_safe)
	{
		if (e->anno_len_const > 0)
		{
			// BCE knows the exact length (new T[N]); comparing against the constant lets gcc drop the check wherever the index range is provably inside.
			cbuf_printf(&u->out, "int64_t n%d_ = (int64_t)%lldLL; ", k, e->anno_len_const);
		}
		else
		{
			cbuf_printf(&u->out, "int64_t n%d_ = *(int64_t *)(a%d_ + 24); ", k, k);
		}

		cbuf_printf(&u->out, "if (__builtin_expect((uint64_t)i%d_ >= (uint64_t)n%d_, 0)) ", k, k);
		cbuf_printf(&u->out, "{ bzy_oob(i%d_, n%d_, (int64_t)(ra - 1), (int64_t)fp); } ", k, k);
	}

	cbuf_printf(&u->out, "(%s *)(a%d_ + 32) + i%d_; }))", et, k, k);
}

/* ((T)((T)l op (T)r)): operands and result in the expression's own type, so narrow arithmetic truncates exactly where the emitter does. */
static void c_arith(CUnit *u, const char *t, const Expr *l, const char *op, const Expr *r)
{
	cbuf_printf(&u->out, "((%s)((%s)", t, t);
	c_expr(u, l);
	cbuf_printf(&u->out, " %s (%s)", op, t);
	c_expr(u, r);
	cbuf_printf(&u->out, "))");
}

/* Integer / and % with a divisor that may be 0 or -1: through the trapping helpers. */
static void c_divide(CUnit *u, const Expr *e, const char *t)
{
	int wide = ty_bits(e->type.kind) == 64;
	int sign = ty_is_signed(e->type.kind) || e->type.kind == TY_BOOL;
	const char *at = NULL;
	if (sign)
	{
		at = wide ? "int64_t" : "int32_t";
	}
	else
	{
		at = wide ? "uint64_t" : "uint32_t";
	}

	cbuf_printf(&u->out, "((%s)bzy_c_%s%s%d((%s)", t, sign ? "s" : "u",
				e->op == TOKEN_SLASH ? "div" : "mod", wide ? 64 : 32, at);
	c_expr(u, e->lhs);
	cbuf_printf(&u->out, ", (%s)", at);
	c_expr(u, e->rhs);
	cbuf_printf(&u->out, "))");
}

/* Comparison of two operands of one type; a literal adopts the other side's type. */
static void c_compare(CUnit *u, const Expr *e, const char *op)
{
	TypeKind lk = e->lhs->type.kind;
	TypeKind rk = e->rhs->type.kind;
	long long dummy = 0;
	if (lk != rk)
	{
		if (c_const_int(e->lhs, &dummy))
		{
			lk = rk;
		}
		else if (c_const_int(e->rhs, &dummy))
		{
			rk = lk;
		}
		else
		{
			u->ok = 0;
			return;
		}
	}

	const char *ct = c_type(lk);
	if (!ct)
	{
		u->ok = 0;
		return;
	}

	cbuf_printf(&u->out, "((int64_t)((%s)", ct);
	c_expr(u, e->lhs);
	cbuf_printf(&u->out, " %s (%s)", op, ct);
	c_expr(u, e->rhs);
	cbuf_printf(&u->out, "))");
}

static void c_binary(CUnit *u, const Expr *e, const char *t)
{
	long long rc = 0;
	switch (e->op)
	{
	case TOKEN_PLUS:
		c_arith(u, t, e->lhs, "+", e->rhs);
		break;
	case TOKEN_MINUS:
		c_arith(u, t, e->lhs, "-", e->rhs);
		break;
	case TOKEN_STAR:
		c_arith(u, t, e->lhs, "*", e->rhs);
		break;
	case TOKEN_AMP:
		c_arith(u, t, e->lhs, "&", e->rhs);
		break;
	case TOKEN_PIPE:
		c_arith(u, t, e->lhs, "|", e->rhs);
		break;
	case TOKEN_CARET:
		c_arith(u, t, e->lhs, "^", e->rhs);
		break;
	case TOKEN_SLASH:
	case TOKEN_PERCENT:
		if (ty_is_float(e->type.kind))
		{
			if (e->op == TOKEN_PERCENT)
			{
				u->ok = 0;
				return;
			}

			c_arith(u, t, e->lhs, "/", e->rhs);
		}
		else if (c_const_value(u, e->rhs, &rc) && rc != 0 && rc != -1)
		{
			c_arith(u, t, e->lhs, e->op == TOKEN_SLASH ? "/" : "%", e->rhs);
		}
		else
		{
			c_divide(u, e, t);
		}

		break;
	case TOKEN_SHL:
	case TOKEN_SHR:
		// Breezy shifts at 64-bit width (sign-extended for signed types, zero-extended for unsigned) with the count masked to 63, then truncates to the type.
		cbuf_printf(&u->out, "((%s)((%s)", t, (ty_is_int(e->type.kind) && !ty_is_signed(e->type.kind)) ? "uint64_t" : "int64_t");
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, " %s (int)((int64_t)", e->op == TOKEN_SHL ? "<<" : ">>");
		c_expr(u, e->rhs);
		cbuf_printf(&u->out, " & 63)))");
		break;
	case TOKEN_EQ:
		c_compare(u, e, "==");
		break;
	case TOKEN_NEQ:
		c_compare(u, e, "!=");
		break;
	case TOKEN_LT:
		c_compare(u, e, "<");
		break;
	case TOKEN_GT:
		c_compare(u, e, ">");
		break;
	case TOKEN_LTE:
		c_compare(u, e, "<=");
		break;
	case TOKEN_GTE:
		c_compare(u, e, ">=");
		break;
	case TOKEN_AND:
	case TOKEN_OR:
		cbuf_printf(&u->out, "((int64_t)((");
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, ") %s (", e->op == TOKEN_AND ? "&&" : "||");
		c_expr(u, e->rhs);
		cbuf_printf(&u->out, ")))");
		break;
	case TOKEN_XOR:
		if (e->type.kind != TY_BOOL)
		{
			c_arith(u, t, e->lhs, "^", e->rhs);
			break;
		}

		cbuf_printf(&u->out, "((int64_t)(((");
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, ") != 0) != ((");
		c_expr(u, e->rhs);
		cbuf_printf(&u->out, ") != 0)))");
		break;
	default:
		u->ok = 0;
		break;
	}
}

static void c_unary(CUnit *u, const Expr *e, const char *t)
{
	switch (e->op)
	{
	case TOKEN_MINUS:
		cbuf_printf(&u->out, "((%s)(-(%s)", t, t);
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, "))");
		break;
	case TOKEN_TILDE:
		cbuf_printf(&u->out, "((%s)(~(%s)", t, t);
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, "))");
		break;
	case TOKEN_NOT:
		cbuf_printf(&u->out, "((int64_t)!(");
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, "))");
		break;
	default:
		u->ok = 0;
		break;
	}
}

/* A whole-C callee's linker symbol: its asm label without the assembler's '$' escape. */
static const char *c_callee_symbol(const FuncInfo *fi)
{
	return fi->asm_label[0] == '$' ? fi->asm_label + 1 : fi->asm_label;
}

/* A direct call to a function compiled whole to C (ir_c_callee): an ordinary C call, arguments widened as its C signature takes them. */
static void c_user_call(CUnit *u, const Expr *e)
{
	FuncInfo *fi = ir_c_callee(e);
	if (!fi)
	{
		u->ok = 0;
		return;
	}

	int seen = 0;
	for (int i = 0; i < u->ncallee; i++)
	{
		seen |= u->callees[i] == fi;
	}

	if (!seen)
	{
		if (u->ncallee == 16)
		{
			u->ok = 0;
			return;
		}

		u->callees[u->ncallee++] = fi;
	}

	const char *rt = e->type.kind == TY_VOID ? NULL : c_type(e->type.kind);
	if (rt)
	{
		cbuf_printf(&u->out, "((%s)", rt);
	}

	cbuf_printf(&u->out, "%s(", c_callee_symbol(fi));
	for (int i = 0; i < e->arg_count; i++)
	{
		cbuf_printf(&u->out, "%s(%s)(", i ? ", " : "", c_param_type(fi->param_types[i].kind));
		c_expr(u, e->args[i]);
		cbuf_printf(&u->out, ")");
	}

	cbuf_printf(&u->out, rt ? "))" : ")");
}

static void c_expr(CUnit *u, const Expr *e)
{
	if (!u->ok)
	{
		return;
	}

	if (e->kind == EX_CALL && !ir_is_clock_read(e))
	{
		c_user_call(u, e);
		return;
	}

	if (e->kind == EX_METHOD_CALL)
	{
		// A non-throwing integer container call: the runtime function itself, receiver from its frame slot, keys and values widened to 64 bits as the emitter passes them.
		const char *fn = ir_c_call(e);
		if (fn)
		{
			const char *rt = c_type(e->type.kind); // NULL for a void put.
			note_local(u, e->lhs->anno_int, TY_GENERIC);
			if (rt)
			{
				cbuf_printf(&u->out, "((%s)", rt);
			}

			cbuf_printf(&u->out, "%s(l%d", fn, e->lhs->anno_int);
			for (int i = 0; i < e->arg_count; i++)
			{
				cbuf_printf(&u->out, ", (int64_t)(");
				c_expr(u, e->args[i]);
				cbuf_printf(&u->out, ")");
			}

			cbuf_printf(&u->out, rt ? "))" : ")");
			return;
		}

		// An integer push onto a local container: the inline helper, with the receiver read from its frame slot.
		int push = ir_c_push(e);
		if (!push)
		{
			u->ok = 0;
			return;
		}

		note_local(u, e->lhs->anno_int, TY_GENERIC);
		cbuf_printf(&u->out, "%s(l%d, (int64_t)(", push == 2 ? "bzy_c_pq_add" : "bzy_c_vec_add", e->lhs->anno_int);
		c_expr(u, e->args[0]);
		cbuf_printf(&u->out, "))");
		return;
	}

	const char *t = c_type(e->type.kind);
	if (!t)
	{
		u->ok = 0;
		return;
	}

	switch (e->kind)
	{
	case EX_INT:
		if (ty_is_float(e->type.kind))
		{
			cbuf_printf(&u->out, "((double)%lldLL)", e->int_val);
		}
		else
		{
			cbuf_printf(&u->out, "((%s)0x%llxULL)", t, (unsigned long long)e->int_val);
		}

		break;
	case EX_BOOL:
		cbuf_printf(&u->out, "((int64_t)%d)", e->int_val ? 1 : 0);
		break;
	case EX_FLOAT:
		cbuf_printf(&u->out, "((double)%.17g)", e->float_val);
		break;
	case EX_IDENT:
		if (e->anno_final)
		{
			u->ok = 0; // A final array only appears as an index or .length base.
			return;
		}

		if (e->anno_capture || e->anno_int <= 0)
		{
			u->ok = 0;
			return;
		}

		if (ty_is_int(e->type.kind))
		{
			long long cv = 0;
			if (c_local_const(u, e->anno_int, &cv))
			{
				// A constant local reads as its literal, so gcc can fold it.
				cbuf_printf(&u->out, "((%s)0x%llxULL)", t, (unsigned long long)cv);
				break;
			}
		}

		note_local(u, e->anno_int, e->type.kind);
		cbuf_printf(&u->out, "l%d", e->anno_int);
		break;
	case EX_INDEX:
		cbuf_printf(&u->out, "((%s)", t);
		c_index_lvalue(u, e);
		cbuf_printf(&u->out, ")");
		break;
	case EX_FIELD:
		if (e->anno_final)
		{
			u->ok = 0; // A final array only appears as an index or .length base.
			return;
		}

		if (e->lhs && e->lhs->anno_final && strcmp(e->name, "length") == 0)
		{
			cbuf_printf(&u->out, "((%s)%dLL)", t, final_table(e->lhs->anno_final - 1)->count);
			break;
		}

		if (!e->lhs || e->lhs->type.kind != TY_ARRAY || strcmp(e->name, "length") != 0)
		{
			u->ok = 0;
			return;
		}

		cbuf_printf(&u->out, "((%s)*(int64_t *)(", t);
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, " + 24))");
		break;
	case EX_BINARY:
		c_binary(u, e, t);
		break;
	case EX_UNARY:
		c_unary(u, e, t);
		break;
	case EX_CAST:
		if (e->type.kind == TY_BOOL)
		{
			cbuf_printf(&u->out, "((int64_t)((");
			c_expr(u, e->lhs);
			cbuf_printf(&u->out, ") != 0))");
		}
		else
		{
			// ponytail: a double outside the target range converts the way cvttsd2si does at run time; gcc only diverges if it constant-folds such a cast.
			cbuf_printf(&u->out, "((%s)", t);
			c_expr(u, e->lhs);
			cbuf_printf(&u->out, ")");
		}

		break;
	case EX_CALL:
		if (!ir_is_clock_read(e))
		{
			u->ok = 0; // Clock reads are the only calls generated C makes.
			break;
		}

		cbuf_printf(&u->out, "bzy_clock_%s()", strcmp(e->name, "Clock.currentTimeNanos") == 0 ? "nanos" : "millis");
		break;
	default:
		u->ok = 0; // Calls, strings, objects, closures, ++/--.
		break;
	}
}

/* An assignment as a C expression (no trailing semicolon), so it also serves as a `for` post clause. */
static void c_assign_expr(CUnit *u, const Expr *target, const Expr *value)
{
	if (target->kind == EX_IDENT)
	{
		const char *t = c_type(target->type.kind);
		if (!t || ty_is_managed(target->type.kind) || target->anno_capture || target->anno_int <= 0)
		{
			u->ok = 0;
			return;
		}

		note_local(u, target->anno_int, target->type.kind);
		cbuf_printf(&u->out, "l%d = (%s)", target->anno_int, t);
		c_expr(u, value);
		return;
	}

	if (target->kind == EX_INDEX)
	{
		const char *et = c_elem_type(target->type.kind);
		if (!et)
		{
			u->ok = 0;
			return;
		}

		c_index_lvalue(u, target);
		cbuf_printf(&u->out, " = (%s)", et);
		c_expr(u, value);
		return;
	}

	u->ok = 0;
}

static void c_indent(CUnit *u, int depth)
{
	for (int i = 0; i < depth; i++)
	{
		cbuf_printf(&u->out, "\t");
	}
}

static void c_stmt(CUnit *u, const Stmt *s, int depth);

static void c_block(CUnit *u, const Block *b, int depth)
{
	c_indent(u, depth);
	cbuf_printf(&u->out, "{\n");
	for (int i = 0; b && i < b->count && u->ok; i++)
	{
		c_stmt(u, b->stmts[i], depth + 1);
	}

	c_indent(u, depth);
	cbuf_printf(&u->out, "}\n");
}

/* The `for` header: init as a statement before the loop, post as an expression. */
/* Steps an affine recurrence is advanced by at once; see c_affine_jump. */
#define C_AFFINE_STEPS 64

/* 1 when e is the integer local at frame offset off (read directly, not captured). */
static int c_is_local(const Expr *e, int off)
{
	return e && e->kind == EX_IDENT && !e->anno_capture && e->anno_int == off;
}

/**
 * Recognizes `for (...; i < lim; i = i + 1) { x = x * A + B; }` with A and B integer constants, i and x distinct integer locals and lim a literal or another local, and emits ahead of the loop a loop that advances x by C_AFFINE_STEPS iterations at once.
 * Wrapping arithmetic makes the composition exact: k steps of x -> A*x + B are x -> A^k*x + B*(A^(k-1) + ... + A + 1) modulo 2^width.
 * The original loop then runs the remaining iterations, so x and i end with the values the plain loop gives them.
 */
static void c_affine_jump(CUnit *u, const Stmt *s, int depth)
{
	const Expr *cond = s->cond;
	const Stmt *post = s->for_post;
	if (!cond || !post || !s->then_blk || s->then_blk->count != 1 || cond->kind != EX_BINARY || cond->op != TOKEN_LT
			|| cond->lhs->kind != EX_IDENT || post->kind != ST_ASSIGN)
	{
		return;
	}

	int i_off = cond->lhs->anno_int;
	long long one = 0;
	if (!ty_is_int(cond->lhs->type.kind) || !c_is_local(cond->lhs, i_off) || !c_is_local(post->target, i_off)
			|| post->value->kind != EX_BINARY || post->value->op != TOKEN_PLUS || !c_is_local(post->value->lhs, i_off)
			|| !c_const_value(u, post->value->rhs, &one) || one != 1)
	{
		return;
	}

	const Stmt *st = s->then_blk->stmts[0];
	if (st->kind != ST_ASSIGN || st->target->kind != EX_IDENT || st->target->anno_capture || st->target->anno_int <= 0)
	{
		return;
	}

	int x_off = st->target->anno_int;
	TypeKind xk = st->target->type.kind;
	const Expr *v = st->value;
	if (x_off == i_off || !ty_is_int(xk) || v->kind != EX_BINARY || v->op != TOKEN_PLUS || v->type.kind != xk)
	{
		return;
	}

	const Expr *mul = v->lhs;
	const Expr *add = v->rhs;
	if (mul->kind != EX_BINARY || mul->op != TOKEN_STAR)
	{
		mul = v->rhs;
		add = v->lhs;
	}

	long long a = 0;
	long long b = 0;
	if (mul->kind != EX_BINARY || mul->op != TOKEN_STAR || mul->type.kind != xk || !c_const_value(u, add, &b))
	{
		return;
	}

	if (!(c_is_local(mul->lhs, x_off) && c_const_value(u, mul->rhs, &a)) && !(c_is_local(mul->rhs, x_off) && c_const_value(u, mul->lhs, &a)))
	{
		return;
	}

	const Expr *lim = cond->rhs;
	if (lim->type.kind != cond->lhs->type.kind)
	{
		return;
	}

	if (lim->kind != EX_INT && !(lim->kind == EX_IDENT && !lim->anno_capture && lim->anno_int > 0 && lim->anno_int != x_off && lim->anno_int != i_off))
	{
		return;
	}

	// Compose the step C_AFFINE_STEPS times: (A1, B1) then (A2, B2) is x -> A1*A2*x + A2*B1 + B2.
	unsigned long long ka = 1;
	unsigned long long kb = 0;
	for (int k = 0; k < C_AFFINE_STEPS; k++)
	{
		kb = (unsigned long long)a * kb + (unsigned long long)b;
		ka = ka * (unsigned long long)a;
	}

	const char *xt = c_type(xk);
	const char *it = c_type(cond->lhs->type.kind);
	note_local(u, x_off, xk);
	note_local(u, i_off, cond->lhs->type.kind);
	c_indent(u, depth);
	cbuf_printf(&u->out, "for (; l%d < ", i_off);
	c_expr(u, lim);
	cbuf_printf(&u->out, " && (uint64_t)((int64_t)(");
	c_expr(u, lim);
	cbuf_printf(&u->out, ") - (int64_t)l%d) >= %d; l%d = (%s)(l%d + %d))\n", i_off, C_AFFINE_STEPS, i_off, it, i_off, C_AFFINE_STEPS);
	c_indent(u, depth);
	cbuf_printf(&u->out, "{\n");
	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "l%d = (%s)((%s)l%d * (%s)0x%llxULL + (%s)0x%llxULL);\n", x_off, xt, xt, x_off, xt, ka, xt, kb);
	c_indent(u, depth);
	cbuf_printf(&u->out, "}\n");
}

static void c_for(CUnit *u, const Stmt *s, int depth)
{
	c_indent(u, depth);
	cbuf_printf(&u->out, "{\n");
	if (s->for_init)
	{
		c_stmt(u, s->for_init, depth + 1);
	}

	c_affine_jump(u, s, depth + 1);

	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "for (; ");
	if (s->cond)
	{
		c_expr(u, s->cond);
	}
	else
	{
		cbuf_printf(&u->out, "1");
	}

	cbuf_printf(&u->out, "; ");
	if (s->for_post && s->for_post->kind == ST_ASSIGN)
	{
		c_assign_expr(u, s->for_post->target, s->for_post->value);
	}
	else if (s->for_post && s->for_post->kind == ST_EXPR)
	{
		c_expr(u, s->for_post->expr);
	}
	else if (s->for_post)
	{
		u->ok = 0;
		return;
	}

	cbuf_printf(&u->out, ")\n");
	u->loops++;
	c_block(u, s->then_blk, depth + 1);
	u->loops--;
	c_indent(u, depth);
	cbuf_printf(&u->out, "}\n");
}

/**
 * A foreach over a local string, an integer or double array or List/Stack/Queue/Deque (ir_c_foreach): read the length, head and data once, then run the body over each slot.
 * Unswitched on the head like the emitter's own list loop: head 0 (no front removal yet) indexes the data directly, which lets gcc vectorize a pure body; otherwise the ring index wraps with the capacity mask.
 * The list's slots are read without its stripe lock, as the emitter's hoisted value-list loop does: an aligned 8-byte load is atomic.
 */
static void c_foreach(CUnit *u, const Stmt *s, int depth)
{
	const char *vt = c_type(s->decl_type.kind);
	if (!ir_c_foreach(s) || !vt)
	{
		u->ok = 0;
		return;
	}

	int lo = s->expr->anno_int;
	int x = s->decl_offset;
	int id = u->fe++;
	note_local(u, x, s->decl_type.kind);
	if (s->expr->type.kind == TY_ARRAY || s->expr->type.kind == TY_STRING)
	{
		// An array: length at +24, elements packed at their own width from +32.
		// A string has the same layout with unsigned bytes; it is loaded as a plain pointer, since nothing else in an eligible loop can name it.
		int str = s->expr->type.kind == TY_STRING;
		const char *et = str ? "uint8_t" : c_elem_type(s->expr->type.elem->kind);
		note_local(u, lo, str ? TY_GENERIC : TY_ARRAY);
		c_indent(u, depth);
		cbuf_printf(&u->out, "{\n");
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, "int64_t fe%d_n = *(int64_t *)(l%d + 24);\n", id, lo);
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, "const %s *fe%d_d = (const %s *)(l%d + 32);\n", et, id, et, lo);
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, "for (int64_t fe%d_i = 0; fe%d_i < fe%d_n; fe%d_i++)\n", id, id, id, id);
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, "{\n");
		c_indent(u, depth + 2);
		cbuf_printf(&u->out, "l%d = (%s)fe%d_d[fe%d_i];\n", x, vt, id, id);
		u->loops++;
		c_block(u, s->then_blk, depth + 2);
		u->loops--;
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, "}\n");
		c_indent(u, depth);
		cbuf_printf(&u->out, "}\n");
		return;
	}

	note_local(u, lo, TY_GENERIC);
	c_indent(u, depth);
	cbuf_printf(&u->out, "{\n");
	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "int64_t fe%d_n = *(int64_t *)(l%d + 24);\n", id, lo);
	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "int64_t fe%d_h = *(int64_t *)(l%d + 40);\n", id, lo);
	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "int64_t fe%d_m = *(int64_t *)(l%d + 32) - 1;\n", id, lo);
	c_indent(u, depth + 1);
	// Each slot is 8 bytes; a double list stores the double's bits, so it is read through a double view.
	const char *st = s->expr->type.elem->kind == TY_DOUBLE ? "double" : "int64_t";
	cbuf_printf(&u->out, "const %s *fe%d_d = fe%d_n > 0 ? (const %s *)(*(char **)(l%d + 48) + 32) : 0;\n", st, id, id, st, lo);
	for (int ring = 0; ring < 2; ring++)
	{
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, ring ? "else\n" : "if (fe%d_h == 0)\n", id);
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, "for (int64_t fe%d_i = 0; fe%d_i < fe%d_n; fe%d_i++)\n", id, id, id, id);
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, "{\n");
		c_indent(u, depth + 2);
		if (ring)
		{
			cbuf_printf(&u->out, "l%d = (%s)fe%d_d[(fe%d_h + fe%d_i) & fe%d_m];\n", x, vt, id, id, id, id);
		}
		else
		{
			cbuf_printf(&u->out, "l%d = (%s)fe%d_d[fe%d_i];\n", x, vt, id, id);
		}

		u->loops++;
		c_block(u, s->then_blk, depth + 2);
		u->loops--;
		c_indent(u, depth + 1);
		cbuf_printf(&u->out, "}\n");
	}

	c_indent(u, depth);
	cbuf_printf(&u->out, "}\n");
}

/**
 * 1 when integer expression e is cheap and can never trap, so it may be evaluated even on the path that would not have run it.
 * Array reads (bounds checks), calls and division by anything but a constant other than 0 and -1 are excluded; *budget caps the size.
 */
/* 1 when expression e reads the local at frame offset off. */
static int c_reads_local(const Expr *e, int off)
{
	if (!e)
	{
		return 0;
	}

	if (e->kind == EX_IDENT)
	{
		return !e->anno_capture && e->anno_int == off;
	}

	return c_reads_local(e->lhs, off) || c_reads_local(e->rhs, off);
}

static int c_pure(CUnit *u, const Expr *e, int *budget)
{
	if (!e || --*budget < 0 || !(ty_is_int(e->type.kind) || e->type.kind == TY_BOOL))
	{
		return 0;
	}

	long long d = 0;
	switch (e->kind)
	{
	case EX_INT:
	case EX_BOOL:
		return 1;
	case EX_IDENT:
		return !e->anno_capture && e->anno_int > 0;
	case EX_CAST:
		return c_pure(u, e->lhs, budget);
	case EX_UNARY:
		return (e->op == TOKEN_MINUS || e->op == TOKEN_TILDE || e->op == TOKEN_NOT) && c_pure(u, e->lhs, budget);
	case EX_BINARY:
		if (e->op == TOKEN_SLASH || e->op == TOKEN_PERCENT)
		{
			return c_const_value(u, e->rhs, &d) && d != 0 && d != -1 && c_pure(u, e->lhs, budget);
		}

		if (e->op == TOKEN_PLUS || e->op == TOKEN_MINUS || e->op == TOKEN_STAR || e->op == TOKEN_AMP || e->op == TOKEN_PIPE
				|| e->op == TOKEN_CARET || e->op == TOKEN_SHL || e->op == TOKEN_SHR || e->op == TOKEN_EQ || e->op == TOKEN_NEQ
				|| e->op == TOKEN_LT || e->op == TOKEN_GT || e->op == TOKEN_LTE || e->op == TOKEN_GTE)
		{
			return c_pure(u, e->lhs, budget) && c_pure(u, e->rhs, budget);
		}

		return 0;
	default:
		return 0;
	}
}

/**
 * Emits value v of a select arm.
 * `n * 3 + c` (likewise 5 or 9, either operand order) is split by an empty asm barrier after the multiply, so gcc emits a two-part lea and an add instead of one three-part lea, whose three-cycle latency would sit on the loop-carried chain.
 */
static void c_select_value(CUnit *u, const Expr *v, const char *t)
{
	long long c = 0;
	long long k = 0;
	if (v->kind == EX_BINARY && v->op == TOKEN_PLUS)
	{
		const Expr *mul = v->lhs->kind == EX_BINARY && v->lhs->op == TOKEN_STAR ? v->lhs : v->rhs;
		const Expr *add = mul == v->lhs ? v->rhs : v->lhs;
		if (mul->kind == EX_BINARY && mul->op == TOKEN_STAR && c_const_value(u, add, &c)
				&& ((c_const_value(u, mul->lhs, &k) && !c_const_value(u, mul->rhs, &c)) || (c_const_value(u, mul->rhs, &k) && !c_const_value(u, mul->lhs, &c)))
				&& (k == 3 || k == 5 || k == 9))
		{
			c_const_value(u, add, &c);
			int n = u->tmp++;
			cbuf_printf(&u->out, "({ %s m%d_ = (%s)(", t, n, t);
			c_expr(u, mul);
			cbuf_printf(&u->out, "); __asm__(\"\" : \"+r\"(m%d_)); (%s)(m%d_ + (%s)0x%llxULL); })", n, t, n, t, (unsigned long long)c);
			return;
		}
	}

	cbuf_printf(&u->out, "(%s)", t);
	c_expr(u, v);
}

/**
 * `if (c) { x = a; } else { x = b; }` inside a loop, x an integer local and a, b cheap and trap-free, becomes a branch-free mask select: both values are computed and the condition picks one.
 * A data-dependent branch mispredicts often; the select costs a few always-taken ALU ops instead.
 * gcc does not form this select itself. Returns 1 when it emitted the select.
 */
static int c_select(CUnit *u, const Stmt *s, int depth)
{
	if (!u->loops || !s->else_blk || !s->then_blk || s->then_blk->count != 1 || s->else_blk->count != 1)
	{
		return 0;
	}

	const Stmt *ts = s->then_blk->stmts[0];
	const Stmt *es = s->else_blk->stmts[0];
	if (ts->kind != ST_ASSIGN || es->kind != ST_ASSIGN || ts->target->kind != EX_IDENT || es->target->kind != EX_IDENT
			|| ts->target->anno_capture || es->target->anno_capture || ts->target->anno_int <= 0
			|| ts->target->anno_int != es->target->anno_int || !ty_is_int(ts->target->type.kind))
	{
		return 0;
	}

	// Only a recurrence step (both arms compute x from x) gains: a mispredict there stalls the loop-carried chain, while a min or a clamp is cheap or predictable as a branch.
	int budget = 16;
	if (!c_pure(u, ts->value, &budget) || !c_pure(u, es->value, &budget)
			|| !c_reads_local(ts->value, ts->target->anno_int) || !c_reads_local(es->value, ts->target->anno_int))
	{
		return 0;
	}

	const char *t = c_type(ts->target->type.kind);
	int x = ts->target->anno_int;
	int n = u->tmp++;
	note_local(u, x, ts->target->type.kind);
	c_indent(u, depth);
	cbuf_printf(&u->out, "{\n");
	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "%s a%d_ = ", t, n);
	c_select_value(u, es->value, t);
	cbuf_printf(&u->out, ";\n");
	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "%s b%d_ = ", t, n);
	c_select_value(u, ts->value, t);
	cbuf_printf(&u->out, ";\n");
	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "%s k%d_ = (%s)-(%s)((", t, n, t, t);
	c_expr(u, s->cond);
	cbuf_printf(&u->out, ") != 0);\n");
	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "l%d = (%s)(a%d_ ^ ((a%d_ ^ b%d_) & k%d_));\n", x, t, n, n, n, n);
	c_indent(u, depth);
	cbuf_printf(&u->out, "}\n");
	return 1;
}

static void c_stmt(CUnit *u, const Stmt *s, int depth)
{
	if (!u->ok)
	{
		return;
	}

	long long v = 0;
	switch (s->kind)
	{
	case ST_VARDECL:
		// Every local is a function-scope C variable mirroring its frame slot; a declaration without an initializer leaves the slot as it is, exactly as the emitter does.
		if (!c_type(s->decl_type.kind) || s->decl_offset <= 0)
		{
			u->ok = 0;
			return;
		}

		note_local(u, s->decl_offset, s->decl_type.kind);
		if (s->decl_init)
		{
			if (ty_is_managed(s->decl_type.kind))
			{
				u->ok = 0;
				return;
			}

			c_indent(u, depth);
			cbuf_printf(&u->out, "l%d = (%s)", s->decl_offset, c_type(s->decl_type.kind));
			c_expr(u, s->decl_init);
			cbuf_printf(&u->out, ";\n");
		}

		break;
	case ST_ASSIGN:
		c_indent(u, depth);
		c_assign_expr(u, s->target, s->value);
		cbuf_printf(&u->out, ";\n");
		break;
	case ST_EXPR:
		c_indent(u, depth);
		cbuf_printf(&u->out, "(void)(");
		c_expr(u, s->expr);
		cbuf_printf(&u->out, ");\n");
		break;
	case ST_IF:
		if (c_select(u, s, depth))
		{
			break;
		}

		c_indent(u, depth);
		cbuf_printf(&u->out, "if (");
		c_expr(u, s->cond);
		cbuf_printf(&u->out, ")\n");
		c_block(u, s->then_blk, depth);
		if (s->else_blk)
		{
			c_indent(u, depth);
			cbuf_printf(&u->out, "else\n");
			c_block(u, s->else_blk, depth);
		}

		break;
	case ST_WHILE:
		c_indent(u, depth);
		cbuf_printf(&u->out, "while (");
		c_expr(u, s->cond);
		cbuf_printf(&u->out, ")\n");
		u->loops++;
		c_block(u, s->then_blk, depth);
		u->loops--;
		break;
	case ST_FOR:
		c_for(u, s, depth);
		break;
	case ST_FOREACH:
		c_foreach(u, s, depth);
		break;
	case ST_BREAK:
		c_indent(u, depth);
		cbuf_printf(&u->out, "break;\n");
		break;
	case ST_CONTINUE:
		c_indent(u, depth);
		cbuf_printf(&u->out, "continue;\n");
		break;
	case ST_SWITCH:
		if (s->is_match || (!ty_is_int(s->cond->type.kind) && s->cond->type.kind != TY_BOOL))
		{
			u->ok = 0;
			return;
		}

		c_indent(u, depth);
		cbuf_printf(&u->out, "switch ((int64_t)");
		c_expr(u, s->cond);
		cbuf_printf(&u->out, ")\n");
		c_block(u, s->then_blk, depth);
		break;
	case ST_CASE:
		if (s->value && s->value->kind == EX_BOOL)
		{
			v = s->value->int_val;
		}
		else if (!s->value || !c_const_int(s->value, &v))
		{
			u->ok = 0;
			return;
		}

		c_indent(u, depth);
		cbuf_printf(&u->out, "case (int64_t)0x%llxULL: ;\n", (unsigned long long)v);
		break;
	case ST_DEFAULT:
		c_indent(u, depth);
		cbuf_printf(&u->out, "default: ;\n");
		break;
	case ST_RETURN:
		if (u->region)
		{
			u->ok = 0;
			return;
		}

		c_indent(u, depth);
		if (!s->ret_val)
		{
			cbuf_printf(&u->out, "return;\n");
			break;
		}

		cbuf_printf(&u->out, "return (%s)(%s)", u->ret_wide, u->ret_narrow);
		c_expr(u, s->ret_val);
		cbuf_printf(&u->out, ";\n");
		break;
	default:
		u->ok = 0; // Foreach, throw, try, spawn, select, asm.
		break;
	}
}

static void c_prelude_once(void)
{
	if (g_src.n == 0)
	{
		cbuf_printf(&g_src, "%s", C_PRELUDE);
	}
}

/**
 * Loads a region local from its frame slot.
 * A narrow slot is read at its own width (the low bytes); a bool is normalized to 0/1.
 */
static void c_load_slot(int off, TypeKind k)
{
	if (k == TY_BOOL)
	{
		cbuf_printf(&g_src, "\tint64_t l%d = *(uint8_t *)(fp - %d) != 0;\n", off, off);
		return;
	}

	cbuf_printf(&g_src, "\t%s l%d = *(%s *)(fp - %d);\n", c_type(k), off, c_type(k), off);
}

/* Stores a region local back into its full 8-byte slot, sign- or zero-extended the way the emitter keeps narrow locals. */
static void c_store_slot(int off, TypeKind k)
{
	if (k == TY_ARRAY || k == TY_GENERIC)
	{
		return; // Regions never reassign a managed local.
	}

	if (k == TY_DOUBLE)
	{
		cbuf_printf(&g_src, "\t*(double *)(fp - %d) = l%d;\n", off, off);
	}
	else if (ty_is_int(k) && !ty_is_signed(k))
	{
		cbuf_printf(&g_src, "\t*(int64_t *)(fp - %d) = (int64_t)(uint64_t)l%d;\n", off, off);
	}
	else
	{
		cbuf_printf(&g_src, "\t*(int64_t *)(fp - %d) = (int64_t)l%d;\n", off, off);
	}
}

/**
 * The exported region symbol.
 * The body is compiled twice, once for the x86-64-v3 feature level and once for the baseline, and this function picks one at run time.
 * It is what the Breezy frame calls, so its return address (minus one) is the pc a bounds failure reports.
 */
static void c_region_dispatch(const char *sym)
{
	cbuf_printf(&g_src, "__attribute__((target(\"arch=x86-64-v3\"), noinline)) static void %s_v3(char *fp, char *ra)\n{\n\t%s_body(fp, ra);\n}\n", sym, sym);
	cbuf_printf(&g_src, "__attribute__((noinline)) static void %s_base(char *fp, char *ra)\n{\n\t%s_body(fp, ra);\n}\n", sym, sym);
	cbuf_printf(&g_src, "void %s(char *fp)\n{\n\tchar *ra = (char *)__builtin_return_address(0);\n", sym);
	cbuf_printf(&g_src, "\tif (bzy_c_has_v3())\n\t{\n\t\t%s_v3(fp, ra);\n\t}\n\telse\n\t{\n\t\t%s_base(fp, ra);\n\t}\n}\n", sym, sym);
}

static int c_declares_in_block(const Block *b, int off);

/* 1 when statement s (or anything nested in it) declares the local at off. */
static int c_declares(const Stmt *s, int off)
{
	if (!s)
	{
		return 0;
	}

	if ((s->kind == ST_VARDECL || s->kind == ST_FOREACH) && s->decl_offset == off)
	{
		return 1;
	}

	return c_declares(s->for_init, off) || c_declares_in_block(s->then_blk, off) || c_declares_in_block(s->else_blk, off);
}

static int c_declares_in_block(const Block *b, int off)
{
	if (!b)
	{
		return 0;
	}

	for (int i = 0; i < b->count; i++)
	{
		if (c_declares(b->stmts[i], off))
		{
			return 1;
		}
	}

	return 0;
}

int cemit_region(const Func *f, const Stmt *s, int outermost, char *sym, int *offs, int cap, int *noffs)
{
	CUnit u;
	memset(&u, 0, sizeof(u));
	u.ok = 1;
	u.region = 1;
	u.fn = f;
	c_stmt(&u, s, 1);
	if (!u.ok || u.nlocal > cap)
	{
		cbuf_free(&u.out);
		return 0;
	}

	for (int i = 0; i < u.nlocal; i++)
	{
		offs[i] = u.local_off[i];
	}

	*noffs = u.nlocal;

	snprintf(sym, 64, "bzy_creg_%d", g_region_seq++);
	c_prelude_once();
	for (int i = 0; i < u.nfinal; i++)
	{
		c_emit_final(u.finals[i]);
	}

	for (int i = 0; i < u.ncallee; i++)
	{
		// The callee is defined in this file under its label (possibly further down), so a prototype lets the region call it.
		const FuncInfo *fi = u.callees[i];
		TypeKind rk = fi->ret_type.kind;
		cbuf_printf(&g_src, "%s %s(", rk == TY_VOID ? "void" : rk == TY_DOUBLE ? "double" : "int64_t", c_callee_symbol(fi));
		for (int j = 0; j < fi->param_count; j++)
		{
			cbuf_printf(&g_src, "%s%s", j ? ", " : "", c_param_type(fi->param_types[j].kind));
		}

		cbuf_printf(&g_src, "%s);\n", fi->param_count ? "" : "void");
	}

	cbuf_printf(&g_src, "\nstatic inline __attribute__((always_inline)) void %s_body(char *fp, char *ra)\n{\n", sym);
	for (int i = 0; i < u.nlocal; i++)
	{
		c_load_slot(u.local_off[i], u.local_kind[i]);
	}

	cbuf_printf(&g_src, "%s", u.out.n ? u.out.p : "");
	for (int i = 0; i < u.nlocal; i++)
	{
		// A local declared inside an outermost region is out of scope once the region ends and its declaration never runs again (slots are never shared), so its final value is dead.
		// Skipping the store frees gcc from keeping it live across the loop.
		if (outermost && c_declares(s, u.local_off[i]))
		{
			continue;
		}

		c_store_slot(u.local_off[i], u.local_kind[i]);
	}

	cbuf_printf(&g_src, "\t(void)fp;\n\t(void)ra;\n}\n");
	c_region_dispatch(sym);
	cbuf_free(&u.out);
	return 1;
}

/* The C parameter type a Breezy argument arrives in: integers widened to 64 bits. */
static const char *c_param_type(TypeKind k)
{
	if (k == TY_ARRAY)
	{
		return "char *";
	}

	if (k == TY_DOUBLE)
	{
		return "double";
	}

	return "int64_t";
}

static int c_is_param_slot(const Func *f, int off)
{
	for (int j = 0; j < f->param_count; j++)
	{
		if (f->params[j].offset == off)
		{
			return 1;
		}
	}

	return 0;
}

int cemit_func_ok(const Func *f)
{
	TypeKind rk = f->ret_type.kind;
	if (rk != TY_VOID && !c_type(rk))
	{
		return 0;
	}

	CUnit u;
	memset(&u, 0, sizeof(u));
	u.ok = 1;
	u.fn = f;
	u.ret_wide = rk == TY_DOUBLE ? "double" : rk != TY_VOID ? "int64_t" : NULL;
	u.ret_narrow = c_type(rk);
	c_block(&u, f->body, 0);
	cbuf_free(&u.out);
	return u.ok;
}

int cemit_func(const Func *f, const char *label)
{
	TypeKind rk = f->ret_type.kind;
	if (rk != TY_VOID && !c_type(rk))
	{
		return 0;
	}

	CUnit u;
	memset(&u, 0, sizeof(u));
	u.ok = 1;
	u.region = 0;
	u.fn = f;
	if (rk == TY_DOUBLE)
	{
		u.ret_wide = "double";
	}
	else if (rk != TY_VOID)
	{
		u.ret_wide = "int64_t";
	}

	u.ret_narrow = c_type(rk);
	c_block(&u, f->body, 0);
	if (!u.ok)
	{
		cbuf_free(&u.out);
		return 0;
	}

	CBuf params;
	memset(&params, 0, sizeof(params));
	for (int i = 0; i < f->param_count; i++)
	{
		cbuf_printf(&params, "%s%s a%d", i ? ", " : "", c_param_type(f->params[i].type.kind), i);
	}

	const char *plist = params.n ? params.p : "void";
	const char *rt = u.ret_wide ? u.ret_wide : "void";
	int n = g_func_seq++;
	c_prelude_once();
	for (int i = 0; i < u.nfinal; i++)
	{
		c_emit_final(u.finals[i]);
	}

	cbuf_printf(&g_src, "\n%s bzy_cfn_%d(%s) __asm__(\"%s\");\n", rt, n, plist, label);
	cbuf_printf(&g_src, "%s bzy_cfn_%d(%s)\n{\n", rt, n, plist);
	for (int i = 0; i < f->param_count; i++)
	{
		const char *ct = c_type(f->params[i].type.kind);
		cbuf_printf(&g_src, "\t%s l%d = (%s)a%d;\n", ct, f->params[i].offset, ct, i);
	}

	for (int i = 0; i < u.nlocal; i++)
	{
		if (!c_is_param_slot(f, u.local_off[i]))
		{
			cbuf_printf(&g_src, "\t%s l%d = 0;\n", c_type(u.local_kind[i]), u.local_off[i]);
		}
	}

	cbuf_printf(&g_src, "%s}\n", u.out.n ? u.out.p : "");
	cbuf_free(&params);
	cbuf_free(&u.out);
	return 1;
}

const char *cemit_source(void)
{
	return g_src.n ? g_src.p : NULL;
}

void cemit_reset(void)
{
	cbuf_free(&g_src);
	if (g_fin_done)
	{
		memset(g_fin_done, 0, (size_t)g_fin_cap);
	}
}
