#define CEMIT_MAX_LOCALS 256

/* Translation state for one unit. */
typedef struct
{
	CBuf        out;                          /* The unit's statement text. */
	int         ok;                           /* Cleared on the first unsupported construct. */
	int         region;                       /* 1: region unit (bounds failures report through fp). */
	int         tmp;                          /* Counter for statement-expression temporaries. */
	int         nfinal;
	int         finals[64];                   /* Final tables the unit indexes (table index). */
	const char *ret_wide;                     /* Whole function: C return type (NULL for void). */
	const char *ret_narrow;                   /* Whole function: Breezy return type in C. */
	int         nlocal;
	int         local_off[CEMIT_MAX_LOCALS];  /* Frame offset of each referenced local. */
	TypeKind    local_kind[CEMIT_MAX_LOCALS]; /* Its type. */
} CUnit;

/* The C type holding a Breezy scalar or array reference, or NULL. */
static const char *c_type(TypeKind k)
{
	switch (k)
	{
	case TY_BYTE:
		return "int8_t";
	case TY_SHORT:
		return "int16_t";
	case TY_INT:
		return "int32_t";
	case TY_LONG:
		return "int64_t";
	case TY_UBYTE:
		return "uint8_t";
	case TY_USHORT:
		return "uint16_t";
	case TY_UINT:
		return "uint32_t";
	case TY_ULONG:
		return "uint64_t";
	case TY_BOOL:
		return "int64_t";
	case TY_DOUBLE:
		return "double";
	case TY_ARRAY:
		return "char *";
	default:
		return NULL;
	}
}

/* The C type of one array element: bool elements are single bytes. */
static const char *c_elem_type(TypeKind k)
{
	if (k == TY_BOOL)
	{
		return "uint8_t";
	}

	if (k == TY_ARRAY)
	{
		return NULL;
	}

	return c_type(k);
}

/* Records that the unit reads or writes the local at frame offset off. */
static void note_local(CUnit *u, int off, TypeKind k)
{
	for (int i = 0; i < u->nlocal; i++)
	{
		if (u->local_off[i] == off)
		{
			if (u->local_kind[i] != k)
			{
				u->ok = 0;
			}

			return;
		}
	}

	if (u->nlocal == CEMIT_MAX_LOCALS)
	{
		u->ok = 0;
		return;
	}

	u->local_off[u->nlocal] = off;
	u->local_kind[u->nlocal] = k;
	u->nlocal++;
}

/* A literal integer, possibly negated. */
static int c_const_int(const Expr *e, long long *out)
{
	if (e->kind == EX_INT)
	{
		*out = e->int_val;
		return 1;
	}

	if (e->kind == EX_UNARY && e->op == TOKEN_MINUS && e->lhs && e->lhs->kind == EX_INT)
	{
		*out = -e->lhs->int_val;
		return 1;
	}

	return 0;
}

static void c_expr(CUnit *u, const Expr *e);

/* arr[i] as an lvalue. A statement expression evaluates the array and the index
   once, applies the bounds check unless BCE proved it, and yields the element
   pointer. A failing check reports through the enclosing Breezy frame: pc is one
   byte before the region call's return address, frame is fp. */
/* Records that the unit reads final table idx. */
static void note_final(CUnit *u, int idx)
{
	for (int i = 0; i < u->nfinal; i++)
	{
		if (u->finals[i] == idx)
		{
			return;
		}
	}

	if (u->nfinal == 64)
	{
		u->ok = 0;
		return;
	}

	u->finals[u->nfinal++] = idx;
}

/* Defines final table idx as a static const C array, once per translation unit. */
static void c_emit_final(int idx)
{
	if (idx >= g_fin_cap)
	{
		int cap = g_fin_cap ? g_fin_cap : 16;
		while (cap <= idx)
		{
			cap *= 2;
		}

		g_fin_done = realloc(g_fin_done, (size_t)cap);
		memset(g_fin_done + g_fin_cap, 0, (size_t)(cap - g_fin_cap));
		g_fin_cap = cap;
	}

	if (g_fin_done[idx])
	{
		return;
	}

	g_fin_done[idx] = 1;
	const FinalTable *ft = final_table(idx);
	const char *et = c_elem_type(ft->elem);
	cbuf_printf(&g_src, "\nstatic const %s bzy_fin_%d[%d] = {", et, idx, ft->count > 0 ? ft->count : 1);
	for (int k = 0; k < ft->count; k++)
	{
		if (ft->elem == TY_DOUBLE)
		{
			cbuf_printf(&g_src, "%s%.17g", k ? ", " : " ", ft->dvals[k]);
		}
		else
		{
			cbuf_printf(&g_src, "%s(%s)0x%llxULL", k ? ", " : " ", et, (unsigned long long)ft->ivals[k]);
		}
	}

	cbuf_printf(&g_src, "%s };\n", ft->count > 0 ? "" : " 0");
}

static void c_index_lvalue(CUnit *u, const Expr *e)
{
	const char *et = c_elem_type(e->type.kind);
	if (!et || e->lhs->type.kind != TY_ARRAY)
	{
		u->ok = 0;
		return;
	}

	if (e->lhs->anno_final)
	{
		/* A final array: index its static const table directly; the count is a
		   compile-time constant and the frame slot is never touched. */
		int idx = e->lhs->anno_final - 1;
		const FinalTable *ft = final_table(idx);
		note_final(u, idx);
		int k = u->tmp++;
		cbuf_printf(&u->out, "(*({ int64_t i%d_ = (int64_t)", k);
		c_expr(u, e->rhs);
		cbuf_printf(&u->out, "; ");
		if (!e->anno_index_safe)
		{
			if (!u->region)
			{
				u->ok = 0;
				return;
			}

			cbuf_printf(&u->out, "if (__builtin_expect((uint64_t)i%d_ >= (uint64_t)%dULL, 0)) ", k, ft->count);
			cbuf_printf(&u->out, "{ bzy_oob(i%d_, %d, (int64_t)(ra - 1), (int64_t)fp); } ", k, ft->count);
		}

		cbuf_printf(&u->out, "&bzy_fin_%d[i%d_]; }))", idx, k);
		return;
	}

	if (!e->anno_index_safe && !u->region)
	{
		u->ok = 0;   /* A whole C function has no Breezy frame to report a bounds failure through. */
		return;
	}

	int k = u->tmp++;
	cbuf_printf(&u->out, "(*({ char *a%d_ = ", k);
	c_expr(u, e->lhs);
	cbuf_printf(&u->out, "; int64_t i%d_ = (int64_t)", k);
	c_expr(u, e->rhs);
	cbuf_printf(&u->out, "; ");
	if (!e->anno_index_safe)
	{
		if (e->anno_len_const > 0)
		{
			/* BCE knows the exact length (new T[N]); comparing against the constant
			   lets gcc drop the check wherever the index range is provably inside. */
			cbuf_printf(&u->out, "int64_t n%d_ = (int64_t)%lldLL; ", k, e->anno_len_const);
		}
		else
		{
			cbuf_printf(&u->out, "int64_t n%d_ = *(int64_t *)(a%d_ + 24); ", k, k);
		}

		cbuf_printf(&u->out, "if (__builtin_expect((uint64_t)i%d_ >= (uint64_t)n%d_, 0)) ", k, k);
		cbuf_printf(&u->out, "{ bzy_oob(i%d_, n%d_, (int64_t)(ra - 1), (int64_t)fp); } ", k, k);
	}

	cbuf_printf(&u->out, "(%s *)(a%d_ + 32) + i%d_; }))", et, k, k);
}

/* ((T)((T)l op (T)r)): operands and result in the expression's own type, so
   narrow arithmetic truncates exactly where the emitter does. */
static void c_arith(CUnit *u, const char *t, const Expr *l, const char *op, const Expr *r)
{
	cbuf_printf(&u->out, "((%s)((%s)", t, t);
	c_expr(u, l);
	cbuf_printf(&u->out, " %s (%s)", op, t);
	c_expr(u, r);
	cbuf_printf(&u->out, "))");
}

/* Integer / and % with a divisor that may be 0 or -1: through the trapping helpers. */
static void c_divide(CUnit *u, const Expr *e, const char *t)
{
	int wide = ty_bits(e->type.kind) == 64;
	int sign = ty_is_signed(e->type.kind) || e->type.kind == TY_BOOL;
	const char *at = NULL;
	if (sign)
	{
		at = wide ? "int64_t" : "int32_t";
	}
	else
	{
		at = wide ? "uint64_t" : "uint32_t";
	}

	cbuf_printf(&u->out, "((%s)bzy_c_%s%s%d((%s)", t, sign ? "s" : "u",
				e->op == TOKEN_SLASH ? "div" : "mod", wide ? 64 : 32, at);
	c_expr(u, e->lhs);
	cbuf_printf(&u->out, ", (%s)", at);
	c_expr(u, e->rhs);
	cbuf_printf(&u->out, "))");
}

/* Comparison of two operands of one type; a literal adopts the other side's type. */
static void c_compare(CUnit *u, const Expr *e, const char *op)
{
	TypeKind lk = e->lhs->type.kind;
	TypeKind rk = e->rhs->type.kind;
	long long dummy = 0;
	if (lk != rk)
	{
		if (c_const_int(e->lhs, &dummy))
		{
			lk = rk;
		}
		else if (c_const_int(e->rhs, &dummy))
		{
			rk = lk;
		}
		else
		{
			u->ok = 0;
			return;
		}
	}

	const char *ct = c_type(lk);
	if (!ct)
	{
		u->ok = 0;
		return;
	}

	cbuf_printf(&u->out, "((int64_t)((%s)", ct);
	c_expr(u, e->lhs);
	cbuf_printf(&u->out, " %s (%s)", op, ct);
	c_expr(u, e->rhs);
	cbuf_printf(&u->out, "))");
}

static void c_binary(CUnit *u, const Expr *e, const char *t)
{
	long long rc = 0;
	switch (e->op)
	{
	case TOKEN_PLUS:
		c_arith(u, t, e->lhs, "+", e->rhs);
		break;
	case TOKEN_MINUS:
		c_arith(u, t, e->lhs, "-", e->rhs);
		break;
	case TOKEN_STAR:
		c_arith(u, t, e->lhs, "*", e->rhs);
		break;
	case TOKEN_AMP:
		c_arith(u, t, e->lhs, "&", e->rhs);
		break;
	case TOKEN_PIPE:
		c_arith(u, t, e->lhs, "|", e->rhs);
		break;
	case TOKEN_CARET:
		c_arith(u, t, e->lhs, "^", e->rhs);
		break;
	case TOKEN_SLASH:
	case TOKEN_PERCENT:
		if (ty_is_float(e->type.kind))
		{
			if (e->op == TOKEN_PERCENT)
			{
				u->ok = 0;
				return;
			}

			c_arith(u, t, e->lhs, "/", e->rhs);
		}
		else if (c_const_int(e->rhs, &rc) && rc != 0 && rc != -1)
		{
			c_arith(u, t, e->lhs, e->op == TOKEN_SLASH ? "/" : "%", e->rhs);
		}
		else
		{
			c_divide(u, e, t);
		}

		break;
	case TOKEN_SHL:
	case TOKEN_SHR:
		/* Breezy shifts at 64-bit width (sign-extended for signed types, zero-extended
		   for unsigned) with the count masked to 63, then truncates to the type. */
		cbuf_printf(&u->out, "((%s)((%s)", t, (ty_is_int(e->type.kind) && !ty_is_signed(e->type.kind)) ? "uint64_t" : "int64_t");
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, " %s (int)((int64_t)", e->op == TOKEN_SHL ? "<<" : ">>");
		c_expr(u, e->rhs);
		cbuf_printf(&u->out, " & 63)))");
		break;
	case TOKEN_EQ:
		c_compare(u, e, "==");
		break;
	case TOKEN_NEQ:
		c_compare(u, e, "!=");
		break;
	case TOKEN_LT:
		c_compare(u, e, "<");
		break;
	case TOKEN_GT:
		c_compare(u, e, ">");
		break;
	case TOKEN_LTE:
		c_compare(u, e, "<=");
		break;
	case TOKEN_GTE:
		c_compare(u, e, ">=");
		break;
	case TOKEN_AND:
	case TOKEN_OR:
		cbuf_printf(&u->out, "((int64_t)((");
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, ") %s (", e->op == TOKEN_AND ? "&&" : "||");
		c_expr(u, e->rhs);
		cbuf_printf(&u->out, ")))");
		break;
	case TOKEN_XOR:
		if (e->type.kind != TY_BOOL)
		{
			c_arith(u, t, e->lhs, "^", e->rhs);
			break;
		}

		cbuf_printf(&u->out, "((int64_t)(((");
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, ") != 0) != ((");
		c_expr(u, e->rhs);
		cbuf_printf(&u->out, ") != 0)))");
		break;
	default:
		u->ok = 0;
		break;
	}
}

static void c_unary(CUnit *u, const Expr *e, const char *t)
{
	switch (e->op)
	{
	case TOKEN_MINUS:
		cbuf_printf(&u->out, "((%s)(-(%s)", t, t);
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, "))");
		break;
	case TOKEN_TILDE:
		cbuf_printf(&u->out, "((%s)(~(%s)", t, t);
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, "))");
		break;
	case TOKEN_NOT:
		cbuf_printf(&u->out, "((int64_t)!(");
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, "))");
		break;
	default:
		u->ok = 0;
		break;
	}
}

static void c_expr(CUnit *u, const Expr *e)
{
	if (!u->ok)
	{
		return;
	}

	const char *t = c_type(e->type.kind);
	if (!t)
	{
		u->ok = 0;
		return;
	}

	switch (e->kind)
	{
	case EX_INT:
		if (ty_is_float(e->type.kind))
		{
			cbuf_printf(&u->out, "((double)%lldLL)", e->int_val);
		}
		else
		{
			cbuf_printf(&u->out, "((%s)0x%llxULL)", t, (unsigned long long)e->int_val);
		}

		break;
	case EX_BOOL:
		cbuf_printf(&u->out, "((int64_t)%d)", e->int_val ? 1 : 0);
		break;
	case EX_FLOAT:
		cbuf_printf(&u->out, "((double)%.17g)", e->float_val);
		break;
	case EX_IDENT:
		if (e->anno_final)
		{
			u->ok = 0;   /* A final array only appears as an index or .length base. */
			return;
		}

		if (e->anno_capture || e->anno_int <= 0)
		{
			u->ok = 0;
			return;
		}

		note_local(u, e->anno_int, e->type.kind);
		cbuf_printf(&u->out, "l%d", e->anno_int);
		break;
	case EX_INDEX:
		cbuf_printf(&u->out, "((%s)", t);
		c_index_lvalue(u, e);
		cbuf_printf(&u->out, ")");
		break;
	case EX_FIELD:
		if (e->anno_final)
		{
			u->ok = 0;   /* A final array only appears as an index or .length base. */
			return;
		}

		if (e->lhs && e->lhs->anno_final && strcmp(e->name, "length") == 0)
		{
			cbuf_printf(&u->out, "((%s)%dLL)", t, final_table(e->lhs->anno_final - 1)->count);
			break;
		}

		if (!e->lhs || e->lhs->type.kind != TY_ARRAY || strcmp(e->name, "length") != 0)
		{
			u->ok = 0;
			return;
		}

		cbuf_printf(&u->out, "((%s)*(int64_t *)(", t);
		c_expr(u, e->lhs);
		cbuf_printf(&u->out, " + 24))");
		break;
	case EX_BINARY:
		c_binary(u, e, t);
		break;
	case EX_UNARY:
		c_unary(u, e, t);
		break;
	case EX_CAST:
		if (e->type.kind == TY_BOOL)
		{
			cbuf_printf(&u->out, "((int64_t)((");
			c_expr(u, e->lhs);
			cbuf_printf(&u->out, ") != 0))");
		}
		else
		{
			/* ponytail: a double outside the target range converts the way cvttsd2si
			   does at run time; gcc only diverges if it constant-folds such a cast. */
			cbuf_printf(&u->out, "((%s)", t);
			c_expr(u, e->lhs);
			cbuf_printf(&u->out, ")");
		}

		break;
	default:
		u->ok = 0;   /* Calls, strings, objects, closures, ++/--. */
		break;
	}
}

/* An assignment as a C expression (no trailing semicolon), so it also serves
   as a `for` post clause. */
static void c_assign_expr(CUnit *u, const Expr *target, const Expr *value)
{
	if (target->kind == EX_IDENT)
	{
		const char *t = c_type(target->type.kind);
		if (!t || ty_is_managed(target->type.kind) || target->anno_capture || target->anno_int <= 0)
		{
			u->ok = 0;
			return;
		}

		note_local(u, target->anno_int, target->type.kind);
		cbuf_printf(&u->out, "l%d = (%s)", target->anno_int, t);
		c_expr(u, value);
		return;
	}

	if (target->kind == EX_INDEX)
	{
		const char *et = c_elem_type(target->type.kind);
		if (!et)
		{
			u->ok = 0;
			return;
		}

		c_index_lvalue(u, target);
		cbuf_printf(&u->out, " = (%s)", et);
		c_expr(u, value);
		return;
	}

	u->ok = 0;
}

static void c_indent(CUnit *u, int depth)
{
	for (int i = 0; i < depth; i++)
	{
		cbuf_printf(&u->out, "\t");
	}
}

static void c_stmt(CUnit *u, const Stmt *s, int depth);

static void c_block(CUnit *u, const Block *b, int depth)
{
	c_indent(u, depth);
	cbuf_printf(&u->out, "{\n");
	for (int i = 0; b && i < b->count && u->ok; i++)
	{
		c_stmt(u, b->stmts[i], depth + 1);
	}

	c_indent(u, depth);
	cbuf_printf(&u->out, "}\n");
}

/* The `for` header: init as a statement before the loop, post as an expression. */
static void c_for(CUnit *u, const Stmt *s, int depth)
{
	c_indent(u, depth);
	cbuf_printf(&u->out, "{\n");
	if (s->for_init)
	{
		c_stmt(u, s->for_init, depth + 1);
	}

	c_indent(u, depth + 1);
	cbuf_printf(&u->out, "for (; ");
	if (s->cond)
	{
		c_expr(u, s->cond);
	}
	else
	{
		cbuf_printf(&u->out, "1");
	}

	cbuf_printf(&u->out, "; ");
	if (s->for_post && s->for_post->kind == ST_ASSIGN)
	{
		c_assign_expr(u, s->for_post->target, s->for_post->value);
	}
	else if (s->for_post && s->for_post->kind == ST_EXPR)
	{
		c_expr(u, s->for_post->expr);
	}
	else if (s->for_post)
	{
		u->ok = 0;
		return;
	}

	cbuf_printf(&u->out, ")\n");
	c_block(u, s->then_blk, depth + 1);
	c_indent(u, depth);
	cbuf_printf(&u->out, "}\n");
}

static void c_stmt(CUnit *u, const Stmt *s, int depth)
{
	if (!u->ok)
	{
		return;
	}

	long long v = 0;
	switch (s->kind)
	{
	case ST_VARDECL:
		/* Every local is a function-scope C variable mirroring its frame slot; a
		   declaration without an initializer leaves the slot as it is, exactly as
		   the emitter does. */
		if (!c_type(s->decl_type.kind) || s->decl_offset <= 0)
		{
			u->ok = 0;
			return;
		}

		note_local(u, s->decl_offset, s->decl_type.kind);
		if (s->decl_init)
		{
			if (ty_is_managed(s->decl_type.kind))
			{
				u->ok = 0;
				return;
			}

			c_indent(u, depth);
			cbuf_printf(&u->out, "l%d = (%s)", s->decl_offset, c_type(s->decl_type.kind));
			c_expr(u, s->decl_init);
			cbuf_printf(&u->out, ";\n");
		}

		break;
	case ST_ASSIGN:
		c_indent(u, depth);
		c_assign_expr(u, s->target, s->value);
		cbuf_printf(&u->out, ";\n");
		break;
	case ST_EXPR:
		c_indent(u, depth);
		cbuf_printf(&u->out, "(void)(");
		c_expr(u, s->expr);
		cbuf_printf(&u->out, ");\n");
		break;
	case ST_IF:
		c_indent(u, depth);
		cbuf_printf(&u->out, "if (");
		c_expr(u, s->cond);
		cbuf_printf(&u->out, ")\n");
		c_block(u, s->then_blk, depth);
		if (s->else_blk)
		{
			c_indent(u, depth);
			cbuf_printf(&u->out, "else\n");
			c_block(u, s->else_blk, depth);
		}

		break;
	case ST_WHILE:
		c_indent(u, depth);
		cbuf_printf(&u->out, "while (");
		c_expr(u, s->cond);
		cbuf_printf(&u->out, ")\n");
		c_block(u, s->then_blk, depth);
		break;
	case ST_FOR:
		c_for(u, s, depth);
		break;
	case ST_BREAK:
		c_indent(u, depth);
		cbuf_printf(&u->out, "break;\n");
		break;
	case ST_CONTINUE:
		c_indent(u, depth);
		cbuf_printf(&u->out, "continue;\n");
		break;
	case ST_SWITCH:
		if (s->is_match || (!ty_is_int(s->cond->type.kind) && s->cond->type.kind != TY_BOOL))
		{
			u->ok = 0;
			return;
		}

		c_indent(u, depth);
		cbuf_printf(&u->out, "switch ((int64_t)");
		c_expr(u, s->cond);
		cbuf_printf(&u->out, ")\n");
		c_block(u, s->then_blk, depth);
		break;
	case ST_CASE:
		if (s->value && s->value->kind == EX_BOOL)
		{
			v = s->value->int_val;
		}
		else if (!s->value || !c_const_int(s->value, &v))
		{
			u->ok = 0;
			return;
		}

		c_indent(u, depth);
		cbuf_printf(&u->out, "case (int64_t)0x%llxULL: ;\n", (unsigned long long)v);
		break;
	case ST_DEFAULT:
		c_indent(u, depth);
		cbuf_printf(&u->out, "default: ;\n");
		break;
	case ST_RETURN:
		if (u->region)
		{
			u->ok = 0;
			return;
		}

		c_indent(u, depth);
		if (!s->ret_val)
		{
			cbuf_printf(&u->out, "return;\n");
			break;
		}

		cbuf_printf(&u->out, "return (%s)(%s)", u->ret_wide, u->ret_narrow);
		c_expr(u, s->ret_val);
		cbuf_printf(&u->out, ";\n");
		break;
	default:
		u->ok = 0;   /* Foreach, throw, try, spawn, select, asm. */
		break;
	}
}

static void c_prelude_once(void)
{
	if (g_src.n == 0)
	{
		cbuf_printf(&g_src, "%s", C_PRELUDE);
	}
}

/* Loads a region local from its frame slot. A narrow slot is read at its own
   width (the low bytes); a bool is normalized to 0/1. */
static void c_load_slot(int off, TypeKind k)
{
	if (k == TY_BOOL)
	{
		cbuf_printf(&g_src, "\tint64_t l%d = *(uint8_t *)(fp - %d) != 0;\n", off, off);
		return;
	}

	cbuf_printf(&g_src, "\t%s l%d = *(%s *)(fp - %d);\n", c_type(k), off, c_type(k), off);
}

/* Stores a region local back into its full 8-byte slot, sign- or zero-extended
   the way the emitter keeps narrow locals. */
static void c_store_slot(int off, TypeKind k)
{
	if (k == TY_ARRAY)
	{
		return;   /* Regions never reassign a managed local. */
	}

	if (k == TY_DOUBLE)
	{
		cbuf_printf(&g_src, "\t*(double *)(fp - %d) = l%d;\n", off, off);
	}
	else if (ty_is_int(k) && !ty_is_signed(k))
	{
		cbuf_printf(&g_src, "\t*(int64_t *)(fp - %d) = (int64_t)(uint64_t)l%d;\n", off, off);
	}
	else
	{
		cbuf_printf(&g_src, "\t*(int64_t *)(fp - %d) = (int64_t)l%d;\n", off, off);
	}
}

/* The exported region symbol. The body is compiled twice, once for the
   x86-64-v3 feature level and once for the baseline, and this function picks
   one at run time. It is what the Breezy frame calls, so its return address
   (minus one) is the pc a bounds failure reports. */
static void c_region_dispatch(const char *sym)
{
	cbuf_printf(&g_src, "__attribute__((target(\"arch=x86-64-v3\"), noinline)) static void %s_v3(char *fp, char *ra)\n{\n\t%s_body(fp, ra);\n}\n", sym, sym);
	cbuf_printf(&g_src, "__attribute__((noinline)) static void %s_base(char *fp, char *ra)\n{\n\t%s_body(fp, ra);\n}\n", sym, sym);
	cbuf_printf(&g_src, "void %s(char *fp)\n{\n\tchar *ra = (char *)__builtin_return_address(0);\n", sym);
	cbuf_printf(&g_src, "\tif (bzy_c_has_v3())\n\t{\n\t\t%s_v3(fp, ra);\n\t}\n\telse\n\t{\n\t\t%s_base(fp, ra);\n\t}\n}\n", sym, sym);
}

int cemit_region(const Stmt *s, char *sym, int *offs, int cap, int *noffs)
{
	CUnit u;
	memset(&u, 0, sizeof(u));
	u.ok = 1;
	u.region = 1;
	c_stmt(&u, s, 1);
	if (!u.ok || u.nlocal > cap)
	{
		cbuf_free(&u.out);
		return 0;
	}

	for (int i = 0; i < u.nlocal; i++)
	{
		offs[i] = u.local_off[i];
	}

	*noffs = u.nlocal;

	snprintf(sym, 64, "bzy_creg_%d", g_region_seq++);
	c_prelude_once();
	for (int i = 0; i < u.nfinal; i++)
	{
		c_emit_final(u.finals[i]);
	}

	cbuf_printf(&g_src, "\nstatic inline __attribute__((always_inline)) void %s_body(char *fp, char *ra)\n{\n", sym);
	for (int i = 0; i < u.nlocal; i++)
	{
		c_load_slot(u.local_off[i], u.local_kind[i]);
	}

	cbuf_printf(&g_src, "%s", u.out.n ? u.out.p : "");
	for (int i = 0; i < u.nlocal; i++)
	{
		c_store_slot(u.local_off[i], u.local_kind[i]);
	}

	cbuf_printf(&g_src, "\t(void)fp;\n\t(void)ra;\n}\n");
	c_region_dispatch(sym);
	cbuf_free(&u.out);
	return 1;
}

/* The C parameter type a Breezy argument arrives in: integers widened to 64 bits. */
static const char *c_param_type(TypeKind k)
{
	if (k == TY_ARRAY)
	{
		return "char *";
	}

	if (k == TY_DOUBLE)
	{
		return "double";
	}

	return "int64_t";
}

static int c_is_param_slot(const Func *f, int off)
{
	for (int j = 0; j < f->param_count; j++)
	{
		if (f->params[j].offset == off)
		{
			return 1;
		}
	}

	return 0;
}

int cemit_func(const Func *f, const char *label)
{
	TypeKind rk = f->ret_type.kind;
	if (rk != TY_VOID && !c_type(rk))
	{
		return 0;
	}

	CUnit u;
	memset(&u, 0, sizeof(u));
	u.ok = 1;
	u.region = 0;
	if (rk == TY_DOUBLE)
	{
		u.ret_wide = "double";
	}
	else if (rk != TY_VOID)
	{
		u.ret_wide = "int64_t";
	}

	u.ret_narrow = c_type(rk);
	c_block(&u, f->body, 0);
	if (!u.ok)
	{
		cbuf_free(&u.out);
		return 0;
	}

	CBuf params;
	memset(&params, 0, sizeof(params));
	for (int i = 0; i < f->param_count; i++)
	{
		cbuf_printf(&params, "%s%s a%d", i ? ", " : "", c_param_type(f->params[i].type.kind), i);
	}

	const char *plist = params.n ? params.p : "void";
	const char *rt = u.ret_wide ? u.ret_wide : "void";
	int n = g_func_seq++;
	c_prelude_once();
	for (int i = 0; i < u.nfinal; i++)
	{
		c_emit_final(u.finals[i]);
	}

	cbuf_printf(&g_src, "\n%s bzy_cfn_%d(%s) __asm__(\"%s\");\n", rt, n, plist, label);
	cbuf_printf(&g_src, "%s bzy_cfn_%d(%s)\n{\n", rt, n, plist);
	for (int i = 0; i < f->param_count; i++)
	{
		const char *ct = c_type(f->params[i].type.kind);
		cbuf_printf(&g_src, "\t%s l%d = (%s)a%d;\n", ct, f->params[i].offset, ct, i);
	}

	for (int i = 0; i < u.nlocal; i++)
	{
		if (!c_is_param_slot(f, u.local_off[i]))
		{
			cbuf_printf(&g_src, "\t%s l%d = 0;\n", c_type(u.local_kind[i]), u.local_off[i]);
		}
	}

	cbuf_printf(&g_src, "%s}\n", u.out.n ? u.out.p : "");
	cbuf_free(&params);
	cbuf_free(&u.out);
	return 1;
}

const char *cemit_source(void)
{
	return g_src.n ? g_src.p : NULL;
}

void cemit_reset(void)
{
	cbuf_free(&g_src);
	if (g_fin_done)
	{
		memset(g_fin_done, 0, (size_t)g_fin_cap);
	}
}
